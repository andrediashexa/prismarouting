#!/bin/sh
# Writes the header that puts this tree's version stamp inside the plugin.
#
#   plugin-version-h.sh <repo> <header path>
#
# WHY this exists at all. src/plugins/bpa/bpa.c registered the plugin with
# `.version = "0.1"`, a literal that had not moved in seventy-one releases
# (#291). That string is what `show plugins` reports, and it was the only
# version the loaded dataplane carried - so it was the same on every box ever
# shipped, and nothing on a box could contradict the VERSION file that
# install.sh had just overwritten. A number somebody has to remember to bump
# is a number that does not get bumped, so this one is taken from the build.
#
# WHY it is the SAME STRING install.sh writes into
# /usr/share/prisma-routing/VERSION, byte for byte, rather than a spelling of its
# own: `show version` compares the two and says when they disagree. Two
# spellings of one truth compare unequal on a box that is perfectly fine, and
# a warning that fires when nothing is wrong is a warning that gets ignored on
# the day it means something. tools/version-stamp.sh is where that calculation
# lives - "so there is one place", as that file puts it - and
# PRISMA_VERSION_STAMP is the same override install.sh honours.
#
# WHY the caller may have to hand the stamp over instead. Measured on this
# tree, the same repository read two ways:
#
#   on the host                         0.71.0 (d07ebda)
#   inside the build container          0.71.0 (not a git tree)
#
# because a git WORKTREE keeps its .git as a FILE pointing at a directory
# under the main clone, and that directory is outside the bind mount
# tools/build.sh gives the container. A plugin stamped "not a git tree" would
# disagree with the box's VERSION file on every single build, and `show
# version` would announce a reboot nobody owes. So tools/build.sh reads the
# stamp on the host, where git can see the repository, and passes it in.
#
# WHY it only writes when the content changed: this header is a compile
# dependency of every object in the plugin. Rewriting it unconditionally
# relinks the plugin on every build, including the `ninja` that each of forty
# labs runs before it starts.
set -eu

REPO=${1:?usage: plugin-version-h.sh <repo> <header path>}
OUT=${2:?usage: plugin-version-h.sh <repo> <header path>}

if [ -n "${PRISMA_VERSION_STAMP:-}" ]; then
  stamp=$PRISMA_VERSION_STAMP
else
  stamp=$(sh "$REPO/tools/version-stamp.sh" "$REPO")
fi

# A stamp carrying a double quote or a backslash would not close the string
# literal it is about to become, and the build would fail somewhere in bpa.c
# with an error about a file nobody wrote. Said here, where the cause is.
case $stamp in
  *'"'*|*'\'*)
    echo "plugin-version-h.sh: the version stamp contains a quote or a" >&2
    echo "backslash and cannot become a C string literal: $stamp" >&2
    exit 1 ;;
esac

mkdir -p "$(dirname "$OUT")"
cat > "$OUT.new" <<EOF
/*
 * Generated by tools/plugin-version-h.sh. Not committed, not editable: it is
 * rewritten from tools/version-stamp.sh on every build that changes it.
 */
#ifndef BPA_VERSION_H
#define BPA_VERSION_H

#define BPA_BUILD_VERSION "$stamp"

#endif /* BPA_VERSION_H */
EOF

if [ -f "$OUT" ] && cmp -s "$OUT.new" "$OUT"; then
  rm -f "$OUT.new"
else
  mv "$OUT.new" "$OUT"
fi
