#!/bin/sh
# Writes src/plugins/bpa/bpa_dpdk_syms.h: where, inside the dpdk_plugin.so of
# the pinned VPP, the five DPDK functions the transceiver read calls live
# (#590).
#
#   sh tools/dpdk-symbols.sh           in the dev image, through docker
#   sh tools/dpdk-symbols.sh --here    already inside it: the header on
#                                      stdout (what the docker run calls, so
#                                      the file is written by the caller and
#                                      owned by them, not by the container's
#                                      root)
#
# WHY OFFSETS AND NOT A LINK. VPP links DPDK statically into dpdk_plugin.so
# and exports none of it: measured on vpp-plugin-dpdk 26.06-release,
# `readelf --dyn-syms` lists 15 defined symbols, the dpdk input and tx node
# functions and three clib_sysfs helpers, and not one rte_*. The shipped
# library is stripped too (.gnu_debuglink only), so neither dlsym() nor
# VPP's own clib_elf_symbol_by_name() can find rte_eth_dev_get_module_eeprom
# at run time. fd.io's vpp-dbg package carries the symbol table of that exact
# build (keyed by its GNU build-id), and that is where this script reads the
# five addresses from.
#
# WHY THAT IS SAFE TO CALL. The header carries the build-id the offsets were
# read against, and the plugin compares it with the build-id of the
# dpdk_plugin.so actually mapped into the running VPP before it calls
# anything: a different build is refused with a sentence, never called into.
# The VPP pin (build/Dockerfile.dev, build/Dockerfile.vpp, the ISO) is the
# same everywhere, and test/test_dpdk_syms.py holds the header's VPP version
# to it, so moving the pin without running this script is red in `make test`
# rather than "unavailable" on a box.
set -eu

REPO=$(cd "$(dirname "$0")/.." && pwd)
OUT_REL=src/plugins/bpa/bpa_dpdk_syms.h
SYMS="rte_eth_dev_is_valid_port rte_eth_macaddr_get rte_eth_dev_get_name_by_port rte_eth_dev_get_module_info rte_eth_dev_get_module_eeprom"

if [ "${1:-}" != "--here" ]; then
  IMAGE=${IMAGE:-prisma-routing-dev:26.06}
  docker run --rm -v "$REPO:/src:ro" -w /src --entrypoint sh "$IMAGE" \
    /src/tools/dpdk-symbols.sh --here > "$REPO/$OUT_REL.new"
  mv "$REPO/$OUT_REL.new" "$REPO/$OUT_REL"
  echo "dpdk-symbols: $OUT_REL: $(grep -o '"[^"]*"' "$REPO/$OUT_REL" | tr '\n' ' ')"
  exit 0
fi

VPP_VERSION=$(dpkg-query -W -f='${Version}' vpp)
if ! dpkg -s vpp-dbg >/dev/null 2>&1; then
  apt-get update -qq >/dev/null 2>&1
  apt-get install -y -qq "vpp-dbg=$VPP_VERSION" >/dev/null 2>&1
fi
LIB=/usr/lib/x86_64-linux-gnu/vpp_plugins/dpdk_plugin.so
ID=$(readelf -n "$LIB" | awk '/Build ID/ { print $3 }')
DBG=/usr/lib/debug/.build-id/$(echo "$ID" | cut -c1-2)/$(echo "$ID" | cut -c3-).debug
[ -f "$DBG" ] || { echo "dpdk-symbols: no debug file $DBG for $LIB" >&2; exit 1; }

{
  echo "/*"
  echo " * GENERATED by tools/dpdk-symbols.sh - do not edit (#590)."
  echo " *"
  echo " * Offsets, from the load address of dpdk_plugin.so, of the DPDK"
  echo " * functions bpa_transceiver.c calls, read from vpp-dbg's symbol table"
  echo " * for the build whose GNU build-id is below. Valid for that build and"
  echo " * no other: the plugin compares the id before it calls anything."
  echo " */"
  echo "#ifndef included_bpa_dpdk_syms_h"
  echo "#define included_bpa_dpdk_syms_h"
  echo
  echo "#define BPA_DPDK_SYMS_VPP_VERSION \"$VPP_VERSION\""
  echo "#define BPA_DPDK_SYMS_BUILD_ID \"$ID\""
  for s in $SYMS; do
    off=$(readelf -sW "$DBG" | awk -v s="$s" '$8 == s && $4 == "FUNC" { print $2; exit }')
    [ -n "$off" ] || { echo "dpdk-symbols: $s is not in $DBG" >&2; exit 1; }
    up=$(echo "$s" | tr 'a-z' 'A-Z')
    echo "#define BPA_DPDK_OFF_$up 0x$(echo "$off" | sed 's/^0*//')"
  done
  echo
  echo "#endif"
}
