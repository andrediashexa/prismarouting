#!/usr/bin/env python3
"""
docs/api-coverage.md against the VTY's grammar (#558).

The document is generated by tools/api-coverage.py from the same tables `?`
answers from. This suite fails when:
  - a VTY command path has no classification (a new top-level word the
    rules do not know is UNCLASSIFIED - add a rule saying how the API
    reaches it);
  - the document is stale (a command or a rule changed and nobody
    regenerated it);
  - a rule names an rpc the proto does not have, or the proto has an rpc
    no rule or document line mentions.
"""
import os
import re
import subprocess
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(REPO, "tools"))
failures = 0


def check(cond, msg):
    global failures
    if cond:
        print(f"  [ ok ] {msg}")
    else:
        print(f"  FAIL: {msg}")
        failures += 1


import importlib.util  # noqa: E402
spec = importlib.util.spec_from_file_location(
    "api_coverage", os.path.join(REPO, "tools", "api-coverage.py"))
cov = importlib.util.module_from_spec(spec)
spec.loader.exec_module(cov)

rows = cov.rows()
check(len(rows) > 300, f"the walk finds the VTY's commands: {len(rows)}")
bad = [r for r in rows if r[3] == "UNCLASSIFIED"]
check(not bad, "every command path has a classification"
      + (": " + ", ".join(f"{r[0]}: {' '.join(r[1])}" for r in bad[:5])
         if bad else ""))

# Each class is what its name says, on a command whose answer is known.
by = {(r[0], " ".join(r[1])): r for r in rows}
check(by.get(("operational", "show version"), (0, 0, 0, ""))[3] == "typed",
      "show version is typed (GetVersion)")
check(by.get(("operational", "show cgnat drops"), (0, 0, 0, ""))[3] == "typed",
      "show cgnat drops is typed (GetDrops, #558 phase 6)")
check(by.get(("operational", "show hardware"), (0, 0, 0, ""))[3] == "typed",
      "show hardware is typed (GetHardware, #558 phase 7)")
check(by.get(("operational", "ping"), (0, 0, 0, ""))[3] == "typed",
      "ping is typed, a stream (Ping, #558 phase 7)")
_text = [" ".join(r[1]) for r in rows if r[3] == "text"]
# `show bfd` is typed since BFD's phase 2 (#559): ListBfdSessions; and the
# last one, `show cgnat ha peer <file>`, since #558's last phase:
# GetHaStatusRequest.peer_path.
check(_text == [], f"no VTY command is left as text (#558): {_text}")
check(by.get(("operational", "show cgnat ha peer"), (0, 0, 0, ""))[3] == "typed"
      and "GetHaStatus" in by.get(("operational", "show cgnat ha peer"),
                                  (0, 0, 0, "", ""))[4],
      "show cgnat ha peer <file> is typed: GetHaStatus with peer_path (#558)")
_doc = open(os.path.join(REPO, "docs", "api-coverage.md")).read()
check("| text | 0 |" in _doc and "| none | 0 |" in _doc,
      "and the summary says so, text 0 and none 0, rather than leaving the "
      "rows out")
check(by.get(("operational", "show bfd peers"), (0, 0, 0, ""))[3] == "typed",
      "show bfd peers is typed (ListBfdSessions, #559 phase 2)")
check(by.get(("operational", "system reboot"), (0, 0, 0, ""))[3] == "typed",
      "system reboot is typed (SystemService.Reboot, #558 phase 5)")
check(not [r for r in rows if r[3] == "none"],
      "no VTY path is unreachable through the API (#558 phase 5): "
      f"{[' '.join(r[1]) for r in rows if r[3] == 'none']}")
check(by.get(("operational", "start shell"), (0, 0, 0, ""))[3] == "n/a",
      "a shell is excluded on purpose")
check(by.get(("pool", "block-size"), (0, 0, 0, ""))[3] == "typed"
      and "GetConfig" in by.get(("pool", "block-size"), (0, 0, 0, "", ""))[4],
      "a pool statement is typed through GetConfig/SetConfig (0.149.20)")
check(by.get(("pool", "no max-blocks"), (0, 0, 0, ""))[3] == "typed",
      "and so is its `no`")
vr = [v for k, v in by.items() if k[0] == "interface (port)" and k[1].startswith("vrrp")]
check(vr and all(v[3] == "typed" and "area vrrp" in v[5] and "written as lines" in v[5]
                 for v in vr),
      "an interface's vrrp is read as fields (area vrrp) and written as lines (0.149.24)")
check(any(k[0] == "cgnat" and k[1].startswith("logging") and v[3] == "typed"
          for k, v in by.items())
      and all(v[3] == "typed" and "cgnat_globals" in v[5] for k, v in by.items()
              if k[0] == "cgnat" and k[1].startswith("timeout")),
      "cgnat: logging typed; the timeouts read as fields in cgnat_globals (0.149.24)")
# #558 phase 4: no CONFIGURATION statement is text any more - what stays text
# is operational (a `show`, a probe), and each config row has a reason.
config_text = [k for k, v in by.items() if v[3] == "text" and "Edit" in v[4]]
check(not config_text,
      f"no configuration statement is text-only after phase 4: {config_text[:5]}")
check(by.get(("bgp neighbor", "neighbor <address> remote-as"), (0, 0, 0, ""))[3] == "typed",
      "a neighbour's remote-as is typed: the two-word grammar key is compared word by word")
check(by.get(("router ospf", "auto-cost reference-bandwidth"), (0, 0, 0, ""))[3] == "typed"
      and "settings" in by[("router ospf", "auto-cost reference-bandwidth")][5],
      "an OSPF knob phase 3 left in `other` is read as a setting (0.149.24)")

# A rule naming an rpc that does not exist would send a reader nowhere.
proto = open(os.path.join(REPO, "api", "prisma", "v1", "prisma.proto")).read()
rpcs = set(re.findall(r"^\s*rpc (\w+)\(", proto, re.M))
named = set()
for r in rows:
    named |= set(re.findall(r"\b([A-Z][A-Za-z]+)\b", r[4].replace(
        "ConfigService", "").replace("OperationalService", "").replace(
        "TelemetryService", "").replace("RouteService", "").replace(
        "SessionService", "").replace("SystemService", "")))
unknown = sorted(n for n in named if n not in rpcs and n not in ("Edit",))
check(not unknown, "every rpc a rule names is in the proto"
      + (f": {unknown}" if unknown else ""))

# The document is what the generator writes now.
p = subprocess.run([sys.executable, os.path.join(REPO, "tools", "api-coverage.py"),
                    "--check"], capture_output=True, text=True)
check(p.returncode == 0, "docs/api-coverage.md is current"
      + (": " + p.stdout.strip().splitlines()[-1] if p.returncode else ""))

print()
if failures:
    print(f"{failures} FAILURES")
    sys.exit(1)
print("ALL TESTS PASSED")
