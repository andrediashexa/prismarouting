#!/usr/bin/env python3
"""
Generates test/bpa_vectors.h from the reference model.

The prefixes go in raw, unmerged: the C has to sort, refuse overlaps and merge
adjacent ranges on its own, and the result is checked against what the Python
model produced.
"""
import ipaddress, os
from bpa_model import PoolConfig, MapPolicy

# name, inside, outside, block size, policy, reserve blocks per public address.
#
# The two reserved pools repeat "frag-interleaved" and "frag-blocked" exactly,
# differing only in the reserve, so the C is compared against the model on a
# pair that isolates the parameter. That pairing is what makes the vectors a
# measurement of what a reserve costs rather than a table of numbers with
# nothing to compare them to.
# name, inside, outside, block size, policy, and an OPTIONS DICT for anything
# a pool needs beyond those.
#
# A dict and not more positional fields. Two of those arrived independently -
# a port range and a reserve - and each took the same position, so the two
# could not be merged without one silently reading the other's number. Named
# options do not collide, and a pool that needs neither says nothing.
#
# The two reserved pools repeat "frag-interleaved" and "frag-blocked" exactly,
# differing only in the reserve, so the C is compared against the model on a
# pair that isolates the parameter. That pairing is what makes the vectors a
# measurement of what a reserve costs rather than a table of numbers with
# nothing to compare them to.
POOLS = [
    ("contiguous", ["100.64.0.0/22"], ["200.150.0.10/31"], 512, MapPolicy.INTERLEAVED),
    ("frag-interleaved", ["100.64.0.0/22"],
     ["200.150.0.8/30", "45.170.16.64/31", "203.0.113.200/32"], 512, MapPolicy.INTERLEAVED),
    ("frag-blocked", ["100.64.0.0/22"],
     ["200.150.0.8/30", "45.170.16.64/31", "203.0.113.200/32"], 512, MapPolicy.BLOCKED),
    ("inside-frag", ["100.64.0.0/24", "10.20.0.0/24"],
     ["200.150.0.0/29", "45.170.16.0/30"], 1024, MapPolicy.INTERLEAVED),
    # adjacent and out-of-order prefixes: exercises merging and sorting in C
    ("adjacent", ["100.64.0.0/23"],
     ["200.150.0.128/25", "200.150.0.0/25"], 2048, MapPolicy.BLOCKED),
    ("narrow-ports", ["100.64.0.0/24"],
     ["200.150.0.16/29"], 256, MapPolicy.INTERLEAVED,
     {"port_min": 2048, "port_max": 20479}),
    ("reserved-interleaved", ["100.64.0.0/22"],
     ["200.150.0.8/30", "45.170.16.64/31", "203.0.113.200/32"], 512,
     MapPolicy.INTERLEAVED, {"reserve": 3}),
    ("reserved-blocked", ["100.64.0.0/22"],
     ["200.150.0.8/30", "45.170.16.64/31", "203.0.113.200/32"], 512,
     MapPolicy.BLOCKED, {"reserve": 3}),
    # one public address, where the reserve is the top of a single port range
    ("reserved-one-addr", ["100.64.0.0/24"], ["203.0.113.7/32"], 4096,
     MapPolicy.INTERLEAVED, {"reserve": 2}),
]

def raw(prefixes):
    out = []
    for p in prefixes:
        n = ipaddress.IPv4Network(p, strict=True)
        out.append((int(n.network_address), n.num_addresses))
    return out

L = ["/* GENERATED by ref/gen_vectors.py - DO NOT EDIT BY HAND. */",
     "#ifndef __included_bpa_vectors_h__",
     "#define __included_bpa_vectors_h__", "",
     "typedef struct {",
     "  const char *name;",
     "  const u32 *in_bases, *in_counts; u32 n_in;",
     "  const u32 *out_bases, *out_counts; u32 n_out;",
     "  u16 port_min, port_max, block_size, reserve;",
     "  int policy;",
     "  u32 exp_blocks_per_ip, exp_blocks_mapped, exp_reserve_count, exp_capacity;",
     "  u32 exp_inside_count, exp_outside_count;",
     "  u32 exp_in_ranges, exp_out_ranges;",
     "  u32 exp_stride_unit;",
     "} bpa_vec_pool_t;", "",
     "typedef struct { u32 pool, ip_priv, ip_pub; u16 port_lo, port_hi; } bpa_vec_fwd_t;",
     "typedef struct { u32 pool, ip_pub; u16 port; u32 ip_priv; } bpa_vec_rev_t;",
     "",
     "/* Where the stride puts the nth block a subscriber holds. `has` is 0",
     "   when the stride runs off the end of the subscriber's own public",
     "   address, which the plugin must refuse to place rather than wrap. */",
     "typedef struct {",
     "  u32 pool; u16 stride; u32 primary_block, nth;",
     "  int has; u32 block, ip_pub; u16 port_lo;",
     "} bpa_vec_stride_t;", "",
     "/* Where every reserve block of a pool is. `res` is the dense reserve",
     "   index: what the return path resolves a reserve port to, and what the",
     "   allocator shards by. */",
     "typedef struct {",
     "  u32 pool, res, pub_idx, blk_idx, ip_pub; u16 port_lo, port_hi;",
     "} bpa_vec_reserve_t;", ""]

built, fwd, rev, strd, resv = [], [], [], [], []
for pi, entry in enumerate(POOLS):
    # Options are read by NAME and defaulted here, so a pool that predates an
    # option keeps its exact definition and its vectors do not move.
    name, ins, outs, bs, pol = entry[:5]
    opt = entry[5] if len(entry) > 5 else {}
    unknown = set(opt) - {"port_min", "port_max", "reserve"}
    # A misspelled option would otherwise be accepted and default silently,
    # and the vectors would be generated for a pool nobody asked for.
    assert not unknown, f"{name}: no such pool option: {sorted(unknown)}"
    res = opt.get("reserve", 0)
    pmin, pmax = opt.get("port_min", 1024), opt.get("port_max", 65535)
    p = PoolConfig(name, ins, outs, block_size=bs, policy=pol,
                   port_min=pmin, port_max=pmax, block_reserve=res)
    ri, ro = raw(ins), raw(outs)

    L.append(f"static const u32 bpa_in_b_{pi}[] = {{ {', '.join(str(b)+'u' for b,_ in ri)} }};")
    L.append(f"static const u32 bpa_in_c_{pi}[] = {{ {', '.join(str(c)+'u' for _,c in ri)} }};")
    L.append(f"static const u32 bpa_out_b_{pi}[] = {{ {', '.join(str(b)+'u' for b,_ in ro)} }};")
    L.append(f"static const u32 bpa_out_c_{pi}[] = {{ {', '.join(str(c)+'u' for _,c in ro)} }};")

    polc = "BPA_POLICY_INTERLEAVED" if pol is MapPolicy.INTERLEAVED else "BPA_POLICY_BLOCKED"
    built.append(f'  {{ "{name}", bpa_in_b_{pi}, bpa_in_c_{pi}, {len(ri)}u, '
                 f'bpa_out_b_{pi}, bpa_out_c_{pi}, {len(ro)}u, '
                 f'{p.port_min}, {p.port_max}, {bs}, {res}, {polc}, '
                 f'{p.blocks_per_ip}u, {p.blocks_mapped}u, '
                 f'{p.reserve_count}u, {p.capacity}u, {p.inside.count}u, '
                 f'{p.outside.count}u, {len(p.inside.ranges)}u, '
                 f'{len(p.outside.ranges)}u, {p.stride_unit}u }},')

    # Every reserve block, not a sample: there are outside.count * reserve of
    # them, and the claim is that not one of them is any subscriber's - which
    # a sample cannot make.
    for r in range(p.reserve_count):
        f = p.reserve_forward(r)
        ip = int(ipaddress.IPv4Address(f["ip_pub"]))
        resv.append(f'  {{ {pi}u, {r}u, {f["pub_idx"]}u, {f["blk_idx"]}u, '
                    f'{ip}u, {f["port_lo"]}, {f["port_hi"]} }},')

    n = min(p.capacity, p.inside.count)
    for sub in range(n):
        ip_priv = p.inside.addr_of(sub)
        f = p.forward(ip_priv)
        pub = int(ipaddress.IPv4Address(f["ip_pub"]))
        fwd.append(f'  {{ {pi}u, {ip_priv}u, {pub}u, {f["port_lo"]}, {f["port_hi"]} }},')
        for port in (f["port_lo"], f["port_lo"] + bs // 2, f["port_hi"]):
            back = int(ipaddress.IPv4Address(p.reverse(f["ip_pub"], port)))
            rev.append(f'  {{ {pi}u, {pub}u, {port}, {back}u }},')

    # Where a stride puts the blocks beyond the first. The primary blocks
    # sampled deliberately include the LAST blocks of a public address, which
    # are the ones whose stride steps off the end: a plugin that wrapped
    # instead of refusing would put the subscriber on an address whose blocks
    # its own worker does not own, and every reply would land on the wrong
    # thread.
    probes = sorted(set(
        [0, 1, p.blocks_mapped // 2, p.capacity // 3]
        + [p.join(0, b) for b in range(max(0, p.blocks_mapped - 4), p.blocks_mapped)]
        + [p.join(p.outside.count - 1, p.blocks_mapped - 1)]))
    for stride in (1, 2, 3):
        if stride >= p.blocks_mapped:
            continue
        # The port range too. Leaving it off built the stride pool with the
        # DEFAULT range while the pool under test had another, and the vectors
        # came out disagreeing with a C implementation that was right: C said
        # port_lo 2304 where this said 1280, which is 1024 plus one block
        # rather than 2048 plus one. The generator was wrong, not the plugin.
        q = PoolConfig(name, ins, outs, block_size=bs, policy=pol,
                       port_min=pmin, port_max=pmax, block_stride=stride,
                       block_reserve=res)
        for pb in probes:
            if pb >= q.capacity:
                continue
            for nth in (1, 2, 3):
                blk = q.extension_block(pb, nth)
                if blk is None:
                    strd.append(f'  {{ {pi}u, {stride}, {pb}u, {nth}u, 0, 0u, 0u, 0 }},')
                    continue
                pub_idx, blk_idx = q.split(blk)
                ip = q.outside.addr_of(pub_idx)
                lo = q.port_min + blk_idx * bs
                strd.append(f'  {{ {pi}u, {stride}, {pb}u, {nth}u, 1, {blk}u, '
                            f'{ip}u, {lo} }},')

L.append("")
L.append("static const bpa_vec_pool_t bpa_vec_pools[] = {")
L += built
L.append("};")
L.append(f"#define BPA_VEC_N_POOLS {len(POOLS)}\n")
L.append("static const bpa_vec_fwd_t bpa_vec_fwd[] = {")
L += fwd
L.append("};")
L.append(f"#define BPA_VEC_N_FWD {len(fwd)}\n")
L.append("static const bpa_vec_rev_t bpa_vec_rev[] = {")
L += rev
L.append("};")
L.append(f"#define BPA_VEC_N_REV {len(rev)}\n")
L.append("static const bpa_vec_stride_t bpa_vec_stride[] = {")
L += strd
L.append("};")
L.append(f"#define BPA_VEC_N_STRIDE {len(strd)}\n")
L.append("static const bpa_vec_reserve_t bpa_vec_reserve[] = {")
L += resv
L.append("};")
L.append(f"#define BPA_VEC_N_RESERVE {len(resv)}\n")
L.append("#endif")

dest = os.path.join(os.path.dirname(__file__), "..", "test", "bpa_vectors.h")
open(dest, "w").write("\n".join(L) + "\n")
print(f"generated: {len(POOLS)} pools, {len(fwd)} forward, {len(rev)} reverse, "
      f"{len(strd)} stride, {len(resv)} reserve")
