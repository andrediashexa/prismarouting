#!/usr/bin/env python3
"""
Generates test/bpa_nat64_vectors.h from the reference model (#485, phase 1).

The dataplane's NAT64 arithmetic (src/plugins/bpa/bpa_nat64.h) must compute
what ref/bpa_model.py computes from the specifications: RFC 6052 embedding at
every prefix length, and the subscriber index over IPv6 prefixes. The model
is the oracle; this file only writes its answers down for the C harness.
"""
import ipaddress, os, random
from bpa_model import (rfc6052_embed, AddrSet6, BpaError, NAT64_LENGTHS)

rng = random.Random(485)


def c_bytes(addr: str) -> str:
    b = ipaddress.IPv6Address(addr).packed
    return "{ " + ", ".join(f"0x{x:02x}" for x in b) + " }"


lines = ["/* Generated by ref/gen_nat64_vectors.py - do not edit. */",
         "#ifndef __included_bpa_nat64_vectors_h__",
         "#define __included_bpa_nat64_vectors_h__", ""]

# --- RFC 6052 embedding ---------------------------------------------------
# The section 2.4 table first, verbatim, then random prefixes and addresses
# at every length.
emb = [(p, "192.0.2.33") for p in (
    "2001:db8::/32", "2001:db8:100::/40", "2001:db8:122::/48",
    "2001:db8:122:300::/56", "2001:db8:122:344::/64",
    "2001:db8:122:344::/96", "64:ff9b::/96")]
for _ in range(60):
    ln = rng.choice(NAT64_LENGTHS)
    a = rng.getrandbits(128) & (((1 << ln) - 1) << (128 - ln))
    a &= ~(0xff << 56)                       # the u octet, zero
    p = f"{ipaddress.IPv6Address(a)}/{ln}"
    emb.append((p, str(ipaddress.IPv4Address(rng.getrandbits(32)))))

lines += ["typedef struct { u8 prefix[16]; u8 len; u32 ip4; u8 addr[16]; }"
          " nat64_embed_vec_t;",
          "static const nat64_embed_vec_t nat64_embed_vecs[] = {"]
for p, v4 in emb:
    net = ipaddress.IPv6Network(p)
    out = rfc6052_embed(p, v4)
    lines.append(f"  {{ {c_bytes(str(net.network_address))}, {net.prefixlen}, "
                 f"0x{int(ipaddress.IPv4Address(v4)):08x}u, {c_bytes(out)} }},")
lines += ["};", ""]

# --- the subscriber index -------------------------------------------------
# Each case: inside prefixes, a subscriber length, then sampled addresses
# with the index the model gives (or -1), and the prefix each index maps to.
cases = [
    (["2001:db8::/32"], 56),
    (["2001:db8:1200::/40", "2001:db8:1000::/40"], 60),   # unsorted, apart
    (["2001:db8:aa00::/48", "2001:db8:aa01::/48"], 64),   # adjacent: merged
    (["2001:db8:1:2::/104"], 128),
    (["2001:db8:ff00::/40", "2001:db8:1::/48", "2001:db8:2::/48"], 56),
]
errors = [
    (["2001:db8::/32"], 64, "BPA_SET6_CAPACITY"),        # 2^32 subscribers
    (["2001:db8::/48", "2001:db8::/56"], 64, "BPA_SET6_OVERLAP"),
    (["2001:db8:1::/64"], 56, "BPA_SET6_SHORTER"),
    (["2001:db8::/32"], 20, "BPA_SET6_BAD_SUBLEN"),
]

lines += ["typedef struct { u8 addr[16]; i32 idx; } nat64_sample_t;",
          "typedef struct { u8 prefix[8][16]; u8 len[8]; u32 n; u8 sub_len;"
          " u32 count; u32 n_samples; nat64_sample_t samples[48];"
          " int error; } nat64_set_vec_t;",
          "static const nat64_set_vec_t nat64_set_vecs[] = {"]


def set_case(prefixes, sub_len, error=None):
    nets = [ipaddress.IPv6Network(p) for p in prefixes]
    pre = ", ".join(c_bytes(str(n.network_address)) for n in nets)
    lens = ", ".join(str(n.prefixlen) for n in nets)
    if error:
        return (f"  {{ {{ {pre} }}, {{ {lens} }}, {len(nets)}, {sub_len}, 0, 0,"
                f" {{ }}, {error} }},")
    s = AddrSet6(prefixes, sub_len)
    samples = []
    for _ in range(40):
        n = rng.choice(nets)
        a = int(n.network_address) | (rng.getrandbits(128 - n.prefixlen)
                                       if n.prefixlen < 128 else 0)
        addr = str(ipaddress.IPv6Address(a))
        samples.append((addr, s.index_of(addr)))
    for addr in ("2001:db9::1", "::1", "ffff::"):      # outside every set
        samples.append((addr, s.index_of(addr)))
    smp = ", ".join(f"{{ {c_bytes(a)}, {i if i is not None else -1} }}"
                    for a, i in samples)
    return (f"  {{ {{ {pre} }}, {{ {lens} }}, {len(nets)}, {sub_len}, {s.count},"
            f" {len(samples)}, {{ {smp} }}, BPA_SET6_OK }},")


for prefixes, sub_len in cases:
    lines.append(set_case(prefixes, sub_len))
for prefixes, sub_len, err in errors:
    # the model must refuse the same configurations
    try:
        AddrSet6(prefixes, sub_len)
        raise SystemExit(f"model accepted {prefixes} /{sub_len}")
    except BpaError:
        pass
    lines.append(set_case(prefixes, sub_len, err))
lines += ["};", "", "#endif", ""]

dest = os.path.join(os.path.dirname(__file__), "..", "test",
                    "bpa_nat64_vectors.h")
with open(dest, "w") as f:
    f.write("\n".join(lines))
