#!/usr/bin/env python3
"""
Generates test/bpa_dyn_vectors.h from the reference model (#603).

What a dynamic pool does with an arrival is a SEQUENCE question, so these
vectors are sequences: subscribers arriving, half of the holders leaving, a
reap, and the block every arrival must get - under the least-loaded rule
`policy interleaved` has since #603, and under the stack it replaced, which
test/test_bpa_dyn.c still reaches on a slice built without a share. Between
rounds, the subscribers each public address has, under both.

The churn is the bench's (#475, lab/bench3vm.sh): fill a share of the pool,
fill it to the top, then rounds of half the holders leaving at random and a
fixed number of idle subscribers arriving. The first scenario IS the bench's
pool - eight addresses, fifteen 4096-port blocks each, three workers - and the
others move one thing each: one worker, a worker count that divides the
address count (each address then belongs to one slice), a worker count that
divides nothing, and a wider public set.
"""
import ipaddress, os, random
from bpa_model import PoolConfig, MapPolicy, DynamicSlices, even_spread

OUT_BASE = 0xC8960010  # 200.150.0.16, the base test_bpa_dyn.c's mkpool uses

# name, public addresses, port_max, block size, workers, subscribers,
# fresh arrivals, arrivals per round, rounds, seed
SCENARIOS = [
    ("bench", 8, 65535, 4096, 3, 240, 60, 30, 12, 1),
    ("one-worker", 8, 65535, 4096, 1, 240, 60, 30, 12, 2),
    ("addresses-per-worker", 8, 65535, 4096, 2, 240, 60, 30, 12, 3),
    ("five-on-six", 6, 65535, 8192, 5, 120, 20, 10, 12, 4),
    ("wide", 64, 65535, 16384, 3, 400, 100, 50, 12, 5),
]

OP_ARRIVE, OP_LEAVE, OP_REAP, OP_CHECK = 0, 1, 2, 3


def pool_for(n_out, port_max, bsz):
    lo = ipaddress.IPv4Address(OUT_BASE)
    hi = ipaddress.IPv4Address(OUT_BASE + n_out - 1)
    outs = [str(n) for n in ipaddress.summarize_address_range(lo, hi)]
    return PoolConfig("dyn", ["100.64.0.0/16"], outs, block_size=bsz,
                      policy=MapPolicy.INTERLEAVED, port_min=1024,
                      port_max=port_max)


def run(scn):
    """The op list, with both rules' answers. The sequence of who arrives and
    who leaves is drawn from the least-loaded run's holders and replayed
    against the stack: the two refuse exactly the same subscribers (a slice
    is full or it is not, whichever block it would have given), and that is
    asserted rather than assumed."""
    name, n_out, pmax, bsz, nw, n_subs, fresh, per_round, rounds, seed = scn
    p = pool_for(n_out, pmax, bsz)
    ll = DynamicSlices(p, nw, "least-loaded")
    st = DynamicSlices(p, nw, "stack")
    rnd = random.Random(seed)
    ops, checks = [], []

    def arrive(s):
        a, b = ll.arrive(s), st.arrive(s)
        assert (a is None) == (b is None), f"{name}: rules refuse differently"
        ops.append((OP_ARRIVE, s, 0xFFFFFFFF if a is None else a,
                    0xFFFFFFFF if b is None else b))

    def check(when):
        assert sorted(ll.held) == sorted(st.held)
        checks.append((when, len(ll.held), list(ll.load), list(st.load)))
        ops.append((OP_CHECK, len(checks) - 1, 0, 0))

    subs = list(range(1, n_subs + 1))
    rnd.shuffle(subs)
    for s in subs[:fresh]:
        arrive(s)
    check("fresh")
    for s in subs[fresh:]:
        arrive(s)
    check("full")
    for r in range(1, rounds + 1):
        gone = rnd.sample(sorted(ll.held), len(ll.held) // 2)
        for s in gone:
            ops.append((OP_LEAVE, s, 0, 0))
        ll.leave(gone)
        st.leave(gone)
        ops.append((OP_REAP, 0, 0, 0))
        idle = [s for s in range(1, n_subs + 1) if s not in ll.held]
        for s in rnd.sample(idle, min(per_round, len(idle))):
            arrive(s)
        check(f"round {r}")
    return p, ops, checks


L = ["/* GENERATED by ref/gen_dyn_vectors.py - DO NOT EDIT BY HAND. */",
     "#ifndef __included_bpa_dyn_vectors_h__",
     "#define __included_bpa_dyn_vectors_h__", "",
     "/* One churned pool. ops[op_first .. op_first + n_ops) is its sequence. */",
     "typedef struct {",
     "  const char *name;",
     "  u32 n_out; u16 port_max, block_size; u32 n_workers;",
     "  u32 op_first, n_ops;",
     "} bpa_dyn_vec_scn_t;", "",
     "/* ARRIVE: `sub` takes a block; `ll` is the block the least-loaded rule",
     "   gives it and `st` the one the stack gave, ~0 for refused. LEAVE: `sub`",
     "   goes idle. REAP: every worker releases what went idle. CHECK: compare",
     "   against bpa_dyn_vec_chk[sub]. */",
     "enum { BPA_DV_ARRIVE, BPA_DV_LEAVE, BPA_DV_REAP, BPA_DV_CHECK };",
     "typedef struct { u8 op; u32 sub, ll, st; } bpa_dyn_vec_op_t;", "",
     "/* Subscribers per public address at a checkpoint, under each rule, in",
     "   bpa_dyn_vec_load[first .. first + n_out), the least-loaded rule's",
     "   then the stack's. `even` is the most even spread possible, times",
     "   1000; the spreads are the model's, times 1000, 0 when an address",
     "   has nobody. */",
     "typedef struct {",
     "  u32 scn; const char *when; u32 holders, first;",
     "  u32 even_x1000, ll_x1000, st_x1000;",
     "} bpa_dyn_vec_chk_t;", ""]

all_ops, all_chk, loads, scns = [], [], [], []
for scn in SCENARIOS:
    p, ops, checks = run(scn)
    name, n_out, pmax, bsz, nw = scn[:5]
    base = len(all_chk)
    scns.append(f'  {{ "{name}", {n_out}u, {pmax}, {bsz}, {nw}u, '
                f'{len(all_ops)}u, {len(ops)}u }},')
    for op, sub, ll, st in ops:
        if op == OP_CHECK:
            sub += base
        all_ops.append(f"  {{ {op}, {sub}u, {ll}u, {st}u }},")
    for when, holders, lload, sload in checks:
        def x1000(v):
            return round(1000 * max(v) / min(v)) if min(v) else 0
        ev = even_spread(holders, n_out)
        all_chk.append(f'  {{ {len(scns) - 1}u, "{when}", {holders}u, '
                       f'{len(loads)}u, {round(1000 * ev) if ev else 0}u, '
                       f'{x1000(lload)}u, {x1000(sload)}u }},')
        loads.extend(lload + sload)

L.append("static const bpa_dyn_vec_scn_t bpa_dyn_vec_scn[] = {")
L += scns
L.append("};")
L.append(f"#define BPA_DYN_VEC_N_SCN {len(scns)}\n")
L.append("static const bpa_dyn_vec_op_t bpa_dyn_vec_op[] = {")
L += all_ops
L.append("};")
L.append(f"#define BPA_DYN_VEC_N_OP {len(all_ops)}\n")
L.append("static const bpa_dyn_vec_chk_t bpa_dyn_vec_chk[] = {")
L += all_chk
L.append("};")
L.append(f"#define BPA_DYN_VEC_N_CHK {len(all_chk)}\n")
L.append("static const u32 bpa_dyn_vec_load[] = {")
for i in range(0, len(loads), 16):
    L.append("  " + ", ".join(f"{v}u" for v in loads[i:i + 16]) + ",")
L.append("};")
L.append("")
L.append("#endif")

dest = os.path.join(os.path.dirname(__file__), "..", "test",
                    "bpa_dyn_vectors.h")
open(dest, "w").write("\n".join(L) + "\n")
print(f"generated: {len(scns)} churned pools, {len(all_ops)} operations, "
      f"{len(all_chk)} checkpoints")
