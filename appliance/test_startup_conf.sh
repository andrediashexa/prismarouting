#!/bin/sh
# Proves the generated startup.conf is valid and that VPP stays up with it.
#
# This test was missing. Without it, the tuning wrote into a startup.conf.d
# that VPP does not read - and nothing said so: the box booted, forwarded, and
# delivered half.
set -u
fail=0
say() { echo "  $*"; }
bad() { echo "  FAIL: $*"; fail=$((fail+1)); }

mkdir -p /run/vpp /vpp_plugins /var/log/vpp
(cd /src/.build-vpp && ninja >/dev/null 2>&1)
sh /src/appliance/install.sh >/dev/null 2>&1

# The VTY had never been run from its installed location by any test: the labs
# run it out of the source tree, where config.py happens to sit beside it. So
# "hexash: ModuleNotFoundError" shipped in every ISO, and only a login found it.
echo "=== does the INSTALLED hexash actually start? ==="
sh /src/appliance/install.sh >/dev/null 2>&1
out=$(hexash -c "show rollback" 2>&1)
case "$out" in
  *Traceback*|*ModuleNotFoundError*|*"not found"*)
    bad "the installed hexash does not start:"; echo "$out" | sed 's/^/    /' ;;
  *) say "installed hexash runs: $(echo "$out" | head -1)" ;;
esac
# Every module the VTY imports has to be installed, not a hand-kept list of
# them. Naming files one by one shipped a missing config.py in 0.2.0 and a
# missing vppapi.py the moment the binary API landed.
for m in $(sed -n 's/^import \([a-z_][a-z_]*\)$/\1/p;s/^from \([a-z_][a-z_]*\) import.*/\1/p' \
             /src/src/hexash/hexash.py); do
  [ -f "/src/src/hexash/$m.py" ] || continue
  [ -f "/usr/lib/hexarouting/$m.py" ] \
    && say "module $m.py installed" \
    || bad "hexash imports $m but $m.py was not installed"
done

# VPP is not started until much further down this file, so this can only ask
# whether the installed VTY RUNS - not whether it reaches anything. It used to
# claim "and reaches the dataplane", which was true of a box with no dataplane
# installed at all: the correct "not running" message is not a traceback.
#
# Correcting that claim left a check that still could not fail. Only the word
# "Traceback" reached bad(); every other answer fell through to a catch-all
# that SAID "starts and answers" whatever came back - including nothing at all.
# And the arm that was supposed to be the good one is a dead needle here: none
# of "not answering", "not running" or "cannot reach" is what this path prints,
# so the run below has always landed on the catch-all. The state it never
# looked at is the one that matters to an operator: with no dataplane, an
# empty answer to "show cgnat pool" is indistinguishable from a healthy box
# with no pools configured, and that is the reading that sends somebody to
# look at the CGNAT configuration instead of at VPP.
#
# So: it must answer, and the answer must say why it cannot answer.
out=$(hexash -c "show cgnat pool" 2>&1)
echo "  with no dataplane, 'show cgnat pool' answers: '${out:-<nothing at all>}'"
case "$out" in
  *Traceback*)
    bad "the installed hexash crashes instead of reporting:"
    echo "$out" | sed 's/^/    /' ;;
  "")
    bad "it answered nothing at all - silence here reads as 'no pools'" ;;
  *socket*|*Socket*|*"not answering"*|*"not running"*|*"cannot reach"*|*"did not respond"*)
    say "starts, and says the dataplane is not up yet - which it is not" ;;
  *)
    bad "it named no dataplane trouble, so this reads as an answer: '$out'" ;;
esac

echo
echo "=== does the box know its own version? ==="
HEXA_VERSION_STAMP="0.0.0-test (deadbee)" sh /src/appliance/install.sh >/dev/null 2>&1
stamp=$(cat /usr/share/hexarouting/VERSION 2>/dev/null || echo "")
[ "$stamp" = "0.0.0-test (deadbee)" ] \
  && say "the installed stamp is the one the build passed" \
  || bad "wrong stamp: '$stamp'"
# With no stamp from the build, the installer has to fall back to the
# repository VERSION - and never invent a number.
sh /src/appliance/install.sh >/dev/null 2>&1
stamp=$(cat /usr/share/hexarouting/VERSION 2>/dev/null || echo "")
case "$stamp" in
  "$(cat /src/VERSION)"*) say "no stamp, falls back to the repo VERSION: $stamp" ;;
  *) bad "with no stamp it produced '$stamp', expected it to start with $(cat /src/VERSION)" ;;
esac

echo
echo "=== does the tuning write where VPP reads? ==="
rm -f /etc/vpp/startup.conf
HEXA_SUBSCRIBERS=200000 /usr/lib/hexarouting/apply-tuning >/dev/null 2>&1
[ -s /etc/vpp/startup.conf ] && say "/etc/vpp/startup.conf generated" \
  || bad "/etc/vpp/startup.conf was not generated"
grep -q "GENERATED by hexarouting-tune" /etc/vpp/startup.conf \
  && say "carries the generated marker" || bad "no generated marker"
# Checks something that exists ONLY in the base. The plugins stanza is
# generated, so looking for it here would be a false positive for
# "base concatenated".
grep -q "cli-listen /run/vpp/cli.sock" /etc/vpp/startup.conf \
  && say "operator base concatenated (unix/cli-listen)" \
  || bad "the base was not concatenated"
grep -q "bpa_plugin.so { enable }" /etc/vpp/startup.conf \
  && say "CGNAT plugin enabled in the generated config" \
  || bad "CGNAT plugin missing"
n=$(grep -c "^plugins {" /etc/vpp/startup.conf)
[ "$n" = 1 ] && say "a single plugins stanza" || bad "plugins{} appears $n times"
grep -qE "^(cpu|buffers|memory) \{" /etc/vpp/startup.conf \
  && say "computed stanzas present" || bad "computed stanzas missing"
n=$(grep -c "^cpu {" /etc/vpp/startup.conf)
[ "$n" = 1 ] && say "no duplicated stanza" || bad "cpu{} appears $n times"

echo
echo "=== does VPP come up with that file? ==="
vpp -c /etc/vpp/startup.conf > /tmp/vppstart.log 2>&1 &
VPPPID=$!
n=0
until vppctl show version >/dev/null 2>&1 || [ "$n" -ge 30 ]; do sleep 1; n=$((n+1)); done
if vppctl show version >/dev/null 2>&1; then
  say "up in ${n}s: $(vppctl show version | head -1 | cut -c1-40)"
else
  bad "did not come up"
  tail -12 /tmp/vppstart.log | sed 's/^/    /'
fi

echo
echo "=== did the CGNAT plugin load? ==="
vppctl show plugins 2>/dev/null | grep -q bpa_plugin \
  && say "bpa_plugin loaded" || bad "bpa_plugin did not load"
vppctl show plugins 2>/dev/null | grep -q linux_cp \
  && say "linux_cp loaded" || bad "linux_cp did not load"

echo
echo "=== and does it STAY up? (the ISO restart loop was here) ==="
sleep 5
if kill -0 $VPPPID 2>/dev/null && vppctl show version >/dev/null 2>&1; then
  say "alive after 5s"
else
  bad "it died; last lines of the log:"
  tail -12 /tmp/vppstart.log | sed 's/^/    /'
fi

echo
# THE TUNED PROFILE IS NOT CHECKED HERE, and that is deliberate.
#
# It was, for one shape, for the length of 0.75.1: this file lifted the dpdk
# stanza out of a synthetic tuned box and handed it to VPP. That found what it
# was written for and was then replaced, because
# appliance/test_startup_conf_shapes.sh asks the same question of EVERY shape
# the tuner can write rather than of one, and gives VPP the whole file instead
# of a stanza.
#
# Two readers of one fact is what this repository refuses everywhere else, and
# the weaker of the two is the one that goes. What stays here is what this file
# has always been about: that the tuning lands where VPP reads it, and that a
# box generated in this container starts.

echo
echo "=== is a CGNAT configuration applicable to it? ==="
vppctl bpa pool test inside 100.64.0.0/22 outside 200.150.0.16/30 >/dev/null 2>&1
vppctl show bpa pool | head -1 | grep -q "pool test" \
  && say "pool created in the generated VPP" || bad "could not create a pool"

echo
[ "$fail" = 0 ] && echo "ALL TESTS PASSED" || echo "$fail FAILURES"
exit $fail
